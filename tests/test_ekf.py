"""EKF checks: analytic Jacobians vs central finite differences, and filter consistency.

Run:  python tests/test_ekf.py   (needs results/ecm_theta_2rc.npy from src/fit_ecm.py)
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from data import DT, Q_REF, ROOT  # noqa: E402
from ecm import TREF_X, _ocv, _param, simulate  # noqa: E402
from ekf import coulomb_count, ekf  # noqa: E402
from ocv import OCV  # noqa: E402

OC = OCV()
TAB = (OC.table, OC.s0, OC.ds)


def h(theta, x, i, T):
    xk = 1000.0 / (T + 273.15) - TREF_X
    return _ocv(*TAB, x[0], T)[0] + _param(theta[0], x[0], xk)[0] * i + x[1:].sum()


def f(theta, x, i, T):
    xk = 1000.0 / (T + 273.15) - TREF_X
    out = x.copy()
    out[0] = x[0] + i * DT / (3600 * Q_REF)
    for m in range(len(x) - 1):
        R = _param(theta[1 + 2 * m], x[0], xk)[0]
        tau = _param(theta[2 + 2 * m], x[0], xk)[0]
        a = np.exp(-DT / tau)
        out[1 + m] = a * x[1 + m] + R * (1 - a) * i
    return out


def analytic(theta, x, i, T):
    """Same expressions as in ekf.ekf, written out in numpy."""
    xk = 1000.0 / (T + 273.15) - TREF_X
    n = len(x)
    _, docv = _ocv(*TAB, x[0], T)
    _, dr0 = _param(theta[0], x[0], xk)
    H = np.ones(n)
    H[0] = docv + dr0 * i
    F = np.eye(n)
    for m in range(n - 1):
        R, dR = _param(theta[1 + 2 * m], x[0], xk)
        tau, dtau = _param(theta[2 + 2 * m], x[0], xk)
        a = np.exp(-DT / tau)
        da = a * DT / tau ** 2 * dtau
        F[1 + m, 1 + m] = a
        F[1 + m, 0] = da * x[1 + m] + (dR * (1 - a) - R * da) * i
    return H, F


def numeric(theta, x, i, T, eps=1e-6):
    n = len(x)
    H, F = np.zeros(n), np.zeros((n, n))
    for j in range(n):
        d = np.zeros(n)
        d[j] = eps
        H[j] = (h(theta, x + d, i, T) - h(theta, x - d, i, T)) / (2 * eps)
        F[:, j] = (f(theta, x + d, i, T) - f(theta, x - d, i, T)) / (2 * eps)
    return H, F


def test_jacobians():
    theta = np.load(ROOT / "results" / "ecm_theta_2rc.npy")
    rng = np.random.default_rng(1)
    worst = 0.0
    for _ in range(300):
        # stay away from OCV grid nodes (0.001 apart), where the piecewise-linear derivative jumps
        s = np.floor(rng.uniform(0.05, 0.95) * 1000) / 1000 + 0.0005
        s = s if min(abs(s - k) for k in (0.1, 0.2, 0.4, 0.6, 0.8)) > 1e-4 else s + 0.0002
        x = np.array([s, rng.uniform(-0.1, 0), rng.uniform(-0.1, 0)])
        i, T = rng.uniform(-15, 8), rng.uniform(-20, 30)
        Ha, Fa = analytic(theta, x, i, T)
        Hn, Fn = numeric(theta, x, i, T)
        scale = np.maximum(np.abs(np.r_[Hn, Fn.ravel()]), 1e-3)
        err = np.max(np.abs(np.r_[Ha - Hn, (Fa - Fn).ravel()]) / scale)
        worst = max(worst, err)
    print(f"  worst relative Jacobian error over 300 random states: {worst:.2e}")
    assert worst < 1e-3


def test_noise_free_tracking():
    """Synthetic data generated by the model itself: the EKF must converge from a wrong start and its
    3-sigma band must contain the truth almost everywhere after convergence."""
    theta = np.load(ROOT / "results" / "ecm_theta_2rc.npy")
    n = 60000
    rng = np.random.default_rng(0)
    i = np.repeat(rng.uniform(-8, 4, n // 50), 50)
    T = np.full(n, 25.0)
    s_true = coulomb_count(i, DT, 0.9)
    v = simulate(theta, s_true, T, i, DT, *TAB) + 0.002 * rng.standard_normal(n)
    soc, sig, _ = ekf(theta, v, i, T, DT, *TAB, 0.6, 0.1, 1e-10, 1e-7, 0.002 ** 2)
    late = slice(n // 3, None)
    err = np.abs(soc - s_true)[late]
    cover = np.mean(err <= 3 * sig[late])
    print(f"  synthetic: final err {abs(soc[-1]-s_true[-1])*100:.3f}% SoC, 3-sigma coverage {cover*100:.1f}%")
    assert err.max() < 0.01 and cover > 0.95


